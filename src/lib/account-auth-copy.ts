export const accountAuthCopy = (locale: Locale) => copies[locale];
export function accountErrorText(locale: Locale, error: string) {
  const t = copies[locale];
  return (
    (
      {
        AUTH_INVALID_EMAIL: t.invalidEmail,
        AUTH_INVALID_CODE: t.invalidCode,
        AUTH_EXPIRED: t.expired,
        AUTH_CHANGED: t.changed,
        AUTH_RATE_LIMIT: t.rateLimit,
        AUTH_IDENTITY_USED: t.identityUsed,
        AUTH_UNAVAILABLE: t.unavailable,
      } as Record<string, string>
    )[error] ?? t.failed
  );
}
